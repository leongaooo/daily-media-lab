"""Verify a dated candidate and install it in both checkouts after user acceptance.

The release plan is private operational data. It includes preimages of the scoped
files, candidate hashes and playback evidence. Only scoped source files and the
generated active baseline pointer enter either skill installation.
"""

from __future__ import annotations

import argparse
import base64
from contextlib import ExitStack, contextmanager
from dataclasses import dataclass
from datetime import date, datetime, timezone
import hashlib
import json
import os
from pathlib import Path, PurePosixPath
import re
import shutil
import subprocess
import sys
import tempfile


BASELINE = "skills/news-to-video/assets/production-baseline.json"
POINTER = "skills/news-to-video/assets/active-production-baseline.json"
ENTRY = "skills/news-to-video/scripts/production.py"
UPGRADE = "skills/news-to-video/scripts/upgrade.py"
SIDES = ("local", "public")
PUBLIC_ADAPTER = (
    "skills/news-to-video/assets/public-voice-policy.json",
    "skills/news-to-video/scripts/public_voice.py",
    "skills/news-to-video/scripts/setup_public_voice.py",
    "skills/news-to-video/scripts/test_public_voice.py",
)
LOCAL_POLICY = "skills/news-to-video/assets/voice-policy.json"
GOVERNANCE = {
    "docs/agents/skill-evals.md",
    "docs/agents/skill-maintenance.md",
    "docs/agents/skill-routing.md",
    "registry.md",
}
PUBLIC_DOCS = {
    "README.md",
    "ROADMAP.md",
    "docs/HANDOFF.md",
    "docs/GETTING_STARTED.md",
    "docs/WORKFLOW.md",
    "examples/blender-calibration/README.md",
    "examples/joint-directing-minimal/README.md",
    "examples/three-media-minimal/README.md",
}
PUBLIC_PRIVATE_TEXT = (
    re.compile(r"[a-z]:[/\\](?:Codex(?:Media)?|Users[/\\]xc_sc|Dreamwork)(?:[/\\]|$)", re.I),
    re.compile(r"(?i)private[-_]voice\.(?:wav|flac|mp3)"),
    re.compile(r"(?i)\b(?:sk-[a-z0-9_-]{24,}|ghp_[a-z0-9]{30,})\b"),
)


@dataclass(frozen=True)
class Change:
    relative: str
    before: str | None
    contents: bytes | None

    @property
    def after(self):
        return digest(self.contents)


def digest(data):
    return hashlib.sha256(data).hexdigest() if data is not None else None


def encode(document):
    return (json.dumps(document, ensure_ascii=False, indent=2) + "\n").encode("utf-8")


def read_json(path):
    return json.loads(path.read_bytes())


def text(value, label):
    if not isinstance(value, str) or not value.strip():
        raise ValueError(f"{label}: expected nonempty text")
    return value


def version_key(value):
    match = re.fullmatch(r"(\d{4})\.(\d{2})\.(\d{2})-([1-9]\d*)", text(value, "version"))
    if not match:
        raise ValueError("version must use YYYY.MM.DD-N")
    year, month, day, revision = map(int, match.groups())
    return date(year, month, day), revision


def valid_digest(value):
    return isinstance(value, str) and re.fullmatch(r"[a-f0-9]{64}", value) is not None


def root_path(value, label):
    original = Path(text(value, label))
    path = original.resolve(strict=True)
    if not path.is_dir() or not original.is_absolute():
        raise ValueError(f"{label}: expected a directory")
    return path


def scoped_file(root, relative):
    path = PurePosixPath(relative)
    if (
        path.is_absolute()
        or str(path) != relative
        or not path.parts
        or any(
            not re.fullmatch(r"[A-Za-z0-9_.-]+", part)
            or part in {".", ".."}
            or part.endswith(".")
            or re.fullmatch(r"(?i)(?:con|prn|aux|nul|com[1-9]|lpt[1-9])(?:\..*)?", part)
            for part in path.parts
        )
    ):
        raise ValueError(f"Invalid release path: {relative}")
    current = root
    for part in path.parts:
        current = current / part
        if current.is_symlink() or getattr(current, "is_junction", lambda: False)():
            raise ValueError(f"Release path traverses a link: {current}")
    return current


def check_scope(side, relative, *, remove=False):
    if relative == POINTER:
        raise ValueError("The active pointer is generated by the upgrade entry")
    if side == "public" and relative in PUBLIC_ADAPTER:
        raise ValueError(f"Public voice adapter must be preserved: {relative}")
    if relative == LOCAL_POLICY:
        if side == "public" and not remove:
            raise ValueError("Private voice policy may not be exported")
        return
    if relative in (GOVERNANCE if side == "local" else PUBLIC_DOCS):
        return
    if side == "public" and re.fullmatch(r"docs/progress/\d{4}-\d\d-\d\d-[a-z0-9-]+\.md", relative):
        return
    script_or_reference = re.fullmatch(
        r"skills/news-to-video/(?:scripts/[\w.-]+\.(?:py|mjs)"
        r"|references/[\w.-]+\.md|evals/[\w.-]+\.(?:json|md)"
        r"|assets/remotion-editorial/[\w.-]+\.(?:tsx?|json)"
        r"|SKILL\.md|CHANGELOG\.md|assets/production-baseline\.json)",
        relative,
    )
    if not script_or_reference:
        raise ValueError(f"{side} release source outside the maintained scope: {relative}")


def existing_bytes(path):
    if path.exists():
        if not path.is_file():
            raise ValueError(f"Release location is not a regular file: {path}")
        return path.read_bytes()
    return None


def atomic_bytes(path, data):
    path.parent.mkdir(parents=True, exist_ok=True)
    with tempfile.NamedTemporaryFile(dir=path.parent, prefix=".upgrade-", delete=False) as stream:
        temporary = Path(stream.name)
        try:
            stream.write(data)
            stream.flush()
            os.fsync(stream.fileno())
        except BaseException:
            stream.close()
            temporary.unlink(missing_ok=True)
            raise
    try:
        temporary.replace(path)
    finally:
        temporary.unlink(missing_ok=True)


def write_file(path, data):
    if data is None:
        path.unlink(missing_ok=True)
    else:
        atomic_bytes(path, data)


def checked_evidence(item, label):
    path = Path(text(item.get("path"), label)).resolve(strict=True)
    sha256 = item.get("sha256")
    if not valid_digest(sha256) or not path.is_file():
        raise ValueError(f"{label}: expected a file identity")
    with path.open("rb") as stream:
        actual = hashlib.file_digest(stream, "sha256").hexdigest()
    if actual != sha256:
        raise ValueError(f"{label}: file changed: {path}")
    return path


def load_plan(plan_path):
    raw = plan_path.read_bytes()
    plan = json.loads(raw)
    if plan.get("schema_version") != 1:
        raise ValueError("Release plan schema_version must be 1")
    version_key(plan.get("version"))
    text(plan.get("scope"), "scope")
    if not isinstance(plan.get("changes"), list) or not plan["changes"]:
        raise ValueError("Release plan must describe at least one change")
    for message in plan["changes"]:
        text(message, "change")
    for message in plan.get("pending", []):
        text(message, "pending item")
    sides = plan.get("sides", {})
    if set(sides) != set(SIDES):
        raise ValueError("Release plan must bind both local and public sides")
    return plan, digest(raw)


def target_roots(plan):
    return {side: root_path(row["target"], f"{side} target") for side, row in plan["sides"].items()}


def load_changes(plan):
    targets = target_roots(plan)
    sources = {
        side: root_path(row["source"], f"{side} candidate")
        for side, row in plan["sides"].items()
    }
    roots = list(targets.values()) + list(sources.values())
    if any(a == b or a in b.parents or b in a.parents for index, a in enumerate(roots) for b in roots[index + 1:]):
        raise ValueError("Candidate and installed roots must be separate")
    private_policy_path = scoped_file(sources["local"], LOCAL_POLICY)
    private_hashes = []
    if private_policy_path.exists():
        private_policy = read_json(private_policy_path)
        private_hashes = [
            value
            for key, value in private_policy.items()
            if key.endswith("_sha256") and valid_digest(value)
        ]
    changes = {}
    baseline_policies = {}
    for side in SIDES:
        row = plan["sides"][side]
        files = row["files"]
        if not {BASELINE, ENTRY, UPGRADE} <= files.keys():
            raise ValueError(f"{side} release must include the baseline and both entry points")
        updated = []
        for relative, hashes in sorted(files.items()):
            remove = hashes.get("after") is None
            check_scope(side, relative, remove=remove)
            data = None if remove else scoped_file(sources[side], relative).read_bytes()
            before, after = hashes.get("before"), hashes.get("after")
            if (before is not None and not valid_digest(before)) or digest(data) != after:
                raise ValueError(f"{side} candidate digest mismatch: {relative}")
            if side == "public" and data is not None:
                content = data.decode("utf-8-sig")
                if any(pattern.search(content) for pattern in PUBLIC_PRIVATE_TEXT) or any(
                    fingerprint in content for fingerprint in private_hashes
                ):
                    raise ValueError(f"Public release contains private data: {relative}")
            updated.append(Change(relative, before, data))
        baseline = next(change for change in updated if change.relative == BASELINE)
        if baseline.contents is None:
            raise ValueError(f"{side} release is missing the baseline")
        policy = json.loads(baseline.contents)
        if policy.get("version") != plan["version"]:
            raise ValueError(f"{side} baseline version differs from the plan")
        baseline_policies[side] = {key: value for key, value in policy.items() if key != "voice"}
        if side == "public" and policy["voice"]["id"] != "qwen-uncle-fu-v1":
            raise ValueError("Public baseline must use the public voice profile")
        pointer = encode({"schema_version": 1, "version": plan["version"], "sha256": baseline.after})
        previous = row.get("active_pointer_before")
        if previous is not None and not valid_digest(previous):
            raise ValueError(f"{side} installed pointer identity is invalid")
        changes[side] = updated + [Change(POINTER, previous, pointer)]
    if baseline_policies["local"] != baseline_policies["public"]:
        raise ValueError("Local and public sides must share the production rules outside the voice adapter")
    if next(c.after for c in changes["local"] if c.relative == UPGRADE) != next(
        c.after for c in changes["public"] if c.relative == UPGRADE
    ):
        raise ValueError("Local and public copies must use the same upgrade entry")
    return sources, targets, changes


def check_public_adapter(plan, target):
    expected = plan["sides"]["public"]["preserve"]
    if not set(PUBLIC_ADAPTER) <= expected.keys():
        raise ValueError("Plan must capture the existing public voice adapter")
    for relative, sha256 in expected.items():
        if not valid_digest(sha256) or digest(existing_bytes(scoped_file(target, relative))) != sha256:
            raise ValueError(f"Preserved public file identity changed: {relative}")


def check_installation(target, changes, version, *, installed):
    for change in changes:
        current = digest(existing_bytes(scoped_file(target, change.relative)))
        expected = change.after if installed else change.before
        if current != expected:
            raise ValueError(f"Installed file changed since release preparation: {target / change.relative}")
    if not installed:
        previous = existing_bytes(scoped_file(target, POINTER))
        if previous is not None and version_key(json.loads(previous)["version"]) >= version_key(version):
            raise ValueError(f"Candidate is stale or already active: {version}")


def run_probes(root, pointer, probes):
    if len(probes) < 2:
        raise ValueError("At least two distinct new-job inputs are required")
    observations = []
    episode_ids = set()
    input_hashes = set()
    for probe in probes:
        episode = checked_evidence(probe, "Inheritance probe episode")
        command = [
            sys.executable, "-B", "-X", "utf8", str(scoped_file(root, ENTRY)),
            "probe", "--episode", str(episode),
        ]
        completed = subprocess.run(command, capture_output=True, encoding="utf-8", timeout=60, check=False)
        if completed.returncode:
            raise ValueError(f"Default production entry rejected {episode.name}: {completed.stderr.strip()}")
        observed = json.loads(completed.stdout)
        expected_episode = text(probe.get("episode_id"), "Probe episode_id")
        if (
            observed.get("selected_by") != "active"
            or observed.get("episode_id") != expected_episode
            or observed.get("version") != pointer["version"]
            or observed.get("sha256") != pointer["sha256"]
        ):
            raise ValueError(f"Default production entry did not inherit this release: {episode.name}")
        # Validate again so the receipt refers to the input the command actually read.
        checked_evidence(probe, "Inheritance probe episode")
        episode_ids.add(expected_episode)
        input_hashes.add(probe["sha256"])
        observations.append({"input": probe, "observed": observed})
    if len(episode_ids) != len(probes) or len(input_hashes) != len(probes):
        raise ValueError("Inheritance probe episodes and input files must be distinct")
    return observations


def summarize(plan, plan_sha, location, observations):
    return {
        "schema_version": 1,
        "version": plan["version"],
        "plan_sha256": plan_sha,
        "scope": plan["scope"],
        "changes": plan["changes"],
        "regression_evidence": plan.get("regression_evidence", []),
        "pending": plan.get("pending", []),
        "observed_at": datetime.now(timezone.utc).isoformat(),
        "checked_installation": location,
        "sides": observations,
        "next_job": "default_entry_inherited_in_checked_installation",
    }


def observe(plan, side, target, changes):
    pointer = read_json(scoped_file(target, POINTER))
    check_installation(target, changes, plan["version"], installed=True)
    if side == "public":
        check_public_adapter(plan, target)
    return {
        "root": str(target),
        "active": pointer,
        "updated_paths": [change.relative for change in changes if change.before != change.after],
        "default_entry_probes": run_probes(target, pointer, plan["probes"]),
    }


def validate_candidate(plan, sha256, sources, targets, changes):
    check_public_adapter(plan, sources["public"])
    observations = {}
    for side in SIDES:
        check_installation(targets[side], changes[side], plan["version"], installed=False)
        with tempfile.TemporaryDirectory(prefix="ntv-check-") as directory:
            isolated = Path(directory)
            skill = isolated / "skills/news-to-video"
            shutil.copytree(
                targets[side] / "skills/news-to-video",
                skill,
                ignore=shutil.ignore_patterns(
                    "__pycache__", ".ruff_cache", "node_modules", "config", "*.tmp",
                ),
            )
            for change in changes[side]:
                write_file(scoped_file(isolated, change.relative), change.contents)
            observations[side] = observe(plan, side, isolated, changes[side])
            observations[side]["root"] = str(sources[side])
    return summarize(plan, sha256, "isolated_candidate", observations)


def check_accepted_media(plan, changes):
    media = plan["accepted_media"]
    files = {kind: checked_evidence(media[kind], kind) for kind in (
        "video", "captions", "production_receipt",
    )}
    production = read_json(files["production_receipt"])
    baseline = next(change for change in changes["local"] if change.relative == BASELINE)
    if (
        production.get("schema_version") != 1
        or production.get("kind") != "production_delivery"
        or production.get("mode") != "revalidate"
        or not production.get("previous_delivery")
        or production["previous_delivery"]["sha256"] == media["video"]["sha256"]
    ):
        raise ValueError("Acceptance needs a new revalidation output and its previous delivery identity")
    actual = production["baseline"]
    if actual["version"] != plan["version"] or actual["sha256"] != baseline.after:
        raise ValueError("The candidate production receipt must use this local baseline version")
    for key, filename in (("video", "video.mp4"), ("captions", "captions.srt")):
        identity = production["artifacts"][filename]
        if identity["sha256"] != media[key]["sha256"] or Path(identity["path"]).resolve() != files[key]:
            raise ValueError(f"Candidate production receipt does not match accepted {key}")
    validation = read_json(checked_evidence(production["artifacts"]["validation.json"], "Render validation"))
    if validation.get("full_decode_passed") is not True or validation.get("production_baseline") != actual:
        raise ValueError("Accepted video must have a complete decode and the same baseline")
    return {"episode_id": production["episode"]["episode_id"], "media": media}


def check_acceptance(plan, sha256, acceptance_path):
    raw = acceptance_path.read_bytes()
    acceptance = json.loads(raw)
    if (
        acceptance.get("schema_version") != 1
        or acceptance.get("kind") != "explicit_user_acceptance"
        or acceptance.get("plan_sha256") != sha256
        or acceptance.get("version") != plan["version"]
    ):
        raise ValueError("Activation requires explicit user acceptance of this exact release plan")
    text(acceptance.get("user_message_reference"), "User acceptance message reference")
    text(acceptance.get("user_quote"), "User acceptance quote")
    for key in ("video", "captions", "production_receipt"):
        if acceptance.get(key + "_sha256") != plan["accepted_media"][key]["sha256"]:
            raise ValueError(f"User acceptance does not bind the candidate {key}")
    return {
        "sha256": digest(raw),
        "user_message_reference": acceptance["user_message_reference"],
        "video_sha256": acceptance["video_sha256"],
    }


@contextmanager
def lock_checkout(root):
    # Keep the lock alongside the checkout, beyond Git's working tree. The OS
    # releases it after an interrupted process; the journal handles file recovery.
    lock = root.parent / ("." + root.name + ".news-to-video-upgrade.lock")
    with lock.open("a+b") as stream:
        if os.name == "nt":
            import msvcrt

            stream.seek(0)
            msvcrt.locking(stream.fileno(), msvcrt.LK_NBLCK, 1)
        else:
            import fcntl

            fcntl.flock(stream.fileno(), fcntl.LOCK_EX | fcntl.LOCK_NB)
        yield


def journal_path(local_root):
    return local_root.parent / ("." + local_root.name + ".news-to-video-upgrade-journal.json")


def backups(targets, changes):
    return {
        side: [
            {
                "relative": change.relative,
                "after": change.after,
                "before": (
                    base64.b64encode(old).decode("ascii")
                    if (old := existing_bytes(scoped_file(targets[side], change.relative))) is not None
                    else None
                ),
            }
            for change in changes[side]
        ]
        for side in SIDES
    }


def restore(path, sha256, targets, changes):
    journal = read_json(path)
    expected_roots = {side: str(root) for side, root in targets.items()}
    if journal["plan_sha256"] != sha256 or journal["targets"] != expected_roots:
        raise ValueError(f"Interrupted release needs recovery with its original plan: {path}")
    # Restore only a file which still matches an exact before/after byte identity.
    # Refuse before touching any file if external edits appeared during recovery.
    operations = []
    for side in reversed(SIDES):
        rows = journal["backups"][side]
        if len(rows) != len(changes[side]):
            raise ValueError(f"Recovery journal contains a different file list: {path}")
        for change, row in reversed(list(zip(changes[side], rows, strict=True))):
            backup = base64.b64decode(row["before"], validate=True) if row["before"] is not None else None
            if row["relative"] != change.relative or row["after"] != change.after or digest(backup) != change.before:
                raise ValueError(f"Recovery journal identity mismatch: {path}")
            target = scoped_file(targets[side], change.relative)
            current = digest(existing_bytes(target))
            if current not in {change.before, change.after}:
                raise ValueError(f"Interrupted release cannot overwrite a later edit: {target}")
            if current != change.before:
                operations.append((target, backup))
    for target, backup in operations:
        write_file(target, backup)
    path.unlink()


def activate(plan, sha256, sources, targets, changes, acceptance_path, receipt_path):
    acceptance = check_acceptance(plan, sha256, acceptance_path)
    accepted_media = check_accepted_media(plan, changes)
    journal = journal_path(targets["local"])
    with ExitStack() as locks:
        for target in sorted(targets.values()):
            locks.enter_context(lock_checkout(target))
        if journal.exists():
            restore(journal, sha256, targets, changes)
        # An already-installed candidate is idempotent only if the scoped files
        # and the real default entry agree with both recorded active pointers.
        if all(
            digest(existing_bytes(scoped_file(targets[side], POINTER))) == changes[side][-1].after
            for side in SIDES
        ):
            receipt = verify_installation(plan, sha256, targets, changes) | {"acceptance": acceptance, "accepted_media": accepted_media}
            atomic_bytes(receipt_path, encode(receipt))
            return receipt
        validate_candidate(plan, sha256, sources, targets, changes)
        check_public_adapter(plan, targets["public"])
        checkpoint = {
            "plan_sha256": sha256,
            "targets": {side: str(root) for side, root in targets.items()},
            "backups": backups(targets, changes),
        }
        atomic_bytes(journal, encode(checkpoint))
        try:
            # Install the source on both sides first. The default entry can see
            # the new baseline only once its validated pointer has been written.
            for pointer_phase in (False, True):
                for side in SIDES:
                    for change in changes[side]:
                        if (change.relative == POINTER) != pointer_phase:
                            continue
                        target = scoped_file(targets[side], change.relative)
                        if digest(existing_bytes(target)) != change.before:
                            raise ValueError(f"Concurrent change during activation: {target}")
                        if change.before != change.after:
                            write_file(target, change.contents)
            receipt = verify_installation(plan, sha256, targets, changes) | {"acceptance": acceptance, "accepted_media": accepted_media}
            atomic_bytes(receipt_path, encode(receipt))
        except BaseException as error:
            try:
                restore(journal, sha256, targets, changes)
            except Exception as recovery_error:
                raise ValueError(f"Activation failed and needs recovery: {error}; {recovery_error}") from recovery_error
            raise
        journal.unlink()
    return receipt


def verify_installation(plan, sha256, targets, changes):
    observations = {
        side: observe(plan, side, targets[side], changes[side])
        for side in SIDES
    }
    return summarize(plan, sha256, "installed_local_and_public_checkouts", observations)


def check_receipt_path(path, targets, sources):
    resolved = path.resolve()
    if any(resolved == root or root in resolved.parents for root in (*targets.values(), *sources.values())):
        raise ValueError("Upgrade receipts must remain in the private release workspace")


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("command", choices=("validate", "activate", "verify"))
    parser.add_argument("plan", type=Path)
    parser.add_argument("--receipt", type=Path)
    parser.add_argument("--acceptance", type=Path)
    args = parser.parse_args()
    try:
        plan, sha256 = load_plan(args.plan)
        sources, targets, changes = load_changes(plan)
        for evidence in plan.get("regression_evidence", []):
            checked_evidence(evidence, "Release regression evidence")
        if args.receipt:
            check_receipt_path(args.receipt, targets, sources)
            if args.receipt.resolve() in {
                args.plan.resolve(),
                args.acceptance.resolve() if args.acceptance else None,
            }:
                raise ValueError("Keep the plan, user acceptance and implementation receipt as separate files")
        if args.command == "validate":
            result = validate_candidate(plan, sha256, sources, targets, changes)
            if "accepted_media" in plan:
                result["accepted_media"] = check_accepted_media(plan, changes)
        elif args.command == "verify":
            result = verify_installation(plan, sha256, targets, changes)
        else:
            if not args.acceptance or not args.receipt:
                parser.error("activate requires --acceptance and --receipt")
            result = activate(plan, sha256, sources, targets, changes, args.acceptance, args.receipt)
        if args.receipt and args.command != "activate":
            atomic_bytes(args.receipt, encode(result))
    except (KeyError, TypeError, ValueError, OSError, subprocess.SubprocessError) as error:
        parser.exit(1, f"Upgrade {args.command} failed: {error}\n")
    print(json.dumps(result, ensure_ascii=False, indent=2))


if __name__ == "__main__":
    main()
